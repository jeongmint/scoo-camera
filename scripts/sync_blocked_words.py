#!/usr/bin/env python3
"""Keeps the blocked-word list for names in one place: shared/blocked_words.txt.

  python3 scripts/sync_blocked_words.py              # check the app and the server match the list
  python3 scripts/sync_blocked_words.py --write      # rewrite the app's list (NameFilter.swift) from the file
  python3 scripts/sync_blocked_words.py --migration  # --write, and add a migration that updates the server

The server side is the newest migration that defines `public.nickname_problem`; a new one is needed whenever
the list changes, since applied migrations are never edited.
"""
import datetime
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
LIST = ROOT / "shared" / "blocked_words.txt"
SWIFT = ROOT / "ios" / "SCOO" / "Models" / "NameFilter.swift"
MIGRATIONS = ROOT / "supabase" / "migrations"
BEGIN = "    // BEGIN blocked words: generated from shared/blocked_words.txt by scripts/sync_blocked_words.py\n"
END = "    // END blocked words\n"


def words_from_file():
    words = []
    for line in LIST.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            words.append(line.lower())
    if len(set(words)) != len(words):
        sys.exit("shared/blocked_words.txt: 같은 말이 두 번 있어요.")
    return words


def swift_words(text):
    block = text[text.index(BEGIN) + len(BEGIN):text.index(END)]
    return re.findall(r'"([^"]+)"', block)


def swift_block(words):
    lines = []
    for i in range(0, len(words), 12):
        lines.append("        " + ", ".join(f'"{w}"' for w in words[i:i + 12]) + ",")
    return BEGIN + "    static let blocked: [String] = [\n" + "\n".join(lines) + "\n    ]\n" + END


def server_file():
    found = [p for p in sorted(MIGRATIONS.glob("*.sql"))
             if "function public.nickname_problem" in p.read_text(encoding="utf-8")]
    return found[-1] if found else None


def server_words(path):
    text = path.read_text(encoding="utf-8")
    block = text[text.index("like any (array["):]
    block = block[:block.index("])")]
    return re.findall(r"'%([^%']+)%'", block)


def migration_sql(words):
    pattern = ",\n        ".join(", ".join(f"'%{w}%'" for w in words[i:i + 10]) for i in range(0, len(words), 10))
    return f"""-- SCOO: the blocked-word list for nicknames changed (shared/blocked_words.txt).
-- Generated by scripts/sync_blocked_words.py; the rules match the app's NameFilter.

create or replace function public.nickname_problem(p_name text) returns text
language sql immutable set search_path = public as $$
    select case
        when p_name is null or btrim(p_name) = '' then '이름을 한 글자 이상 지어 주세요.'
        when char_length(p_name) > 12 then '이름은 12글자까지 지을 수 있어요.'
        when p_name !~ '^[가-힣A-Za-z0-9 ]+$' then '한글(완성된 글자), 영어, 숫자, 띄어쓰기만 쓸 수 있어요.'
        when char_length(regexp_replace(p_name, '[^0-9]', '', 'g')) * 2 > char_length(p_name)
          or p_name ~ '[0-9]{{4,}}' then '숫자가 너무 많아요. 다른 이름으로 지어 주세요.'
        when lower(regexp_replace(p_name, '[^가-힣A-Za-z]', '', 'g')) like any (array[
        {pattern}
        ]) then '쓸 수 없는 말이 들어 있어요. 다른 이름으로 지어 주세요.'
    end
$$;
revoke all on function public.nickname_problem(text) from public, anon;
grant execute on function public.nickname_problem(text) to authenticated;
"""


def main():
    args = set(sys.argv[1:])
    words = words_from_file()
    swift = SWIFT.read_text(encoding="utf-8")
    if "--write" in args or "--migration" in args:
        start, end = swift.index(BEGIN), swift.index(END) + len(END)
        swift = swift[:start] + swift_block(words) + swift[end:]
        SWIFT.write_text(swift, encoding="utf-8")
        print("앱 목록을 맞췄어요:", SWIFT.relative_to(ROOT))
    server = server_file()
    if "--migration" in args and (server is None or server_words(server) != words):
        stamp = datetime.datetime.now(datetime.timezone.utc).strftime("%Y%m%d%H%M%S")
        server = MIGRATIONS / f"{stamp}_blocked_words.sql"
        server.write_text(migration_sql(words), encoding="utf-8")
        print("서버에 적용할 새 마이그레이션:", server.relative_to(ROOT))

    problems = []
    if swift_words(swift) != words:
        problems.append("앱(NameFilter.swift) 목록이 shared/blocked_words.txt 와 달라요. --write 로 맞추세요.")
    if server is None or server_words(server) != words:
        problems.append("서버 마이그레이션 목록이 shared/blocked_words.txt 와 달라요. --migration 으로 새로 만드세요.")
    if problems:
        print("\n".join(problems))
        sys.exit(1)
    print(f"앱과 서버의 목록이 같아요 ({len(words)}개, 서버: {server.name}).")


if __name__ == "__main__":
    main()
